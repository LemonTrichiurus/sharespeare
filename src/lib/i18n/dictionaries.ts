export const LANG_COOKIE = 'lang'

export function isLang(value: unknown): value is Lang {
  return value === 'zh' || value === 'en'
}

export function getDict(lang: Lang): Dict {
  return lang === 'zh' ? zh : en
}

/** Look up a key, filling {placeholders} from params. Falls back to the key itself. */
export function translate(dict: Dict, key: string, params?: Record<string, string | number>): string {
  const text = dict[key] ?? key
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

export function localeOf(lang: Lang): string {
  return lang === 'zh' ? 'zh-CN' : 'en-US'
}

export function formatDate(iso: string, lang: Lang, withYear = true): string {
  return new Date(iso).toLocaleDateString(localeOf(lang), {
    year: withYear ? 'numeric' : undefined,
    month: 'long',
    day: 'numeric',
  })
}
